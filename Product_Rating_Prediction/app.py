def find_file(relative_path):
    """Find file in current directory or Product_Rating_Prediction subfolder."""
    candidates = [
        relative_path,
        os.path.join("Product_Rating_Prediction", relative_path),
        os.path.join("..", relative_path)
    ]
    for c in candidates:
        if os.path.exists(c):
            return os.path.abspath(c)
    return None


