def predict_single(category, price, review_text, verified_purchase, review_count, avg_rating, metadata, word_map=None):
    """
    Transform single input using trained pipeline stages:
    1. Categorical one-hot encoding
    2. Review text TF-IDF vector matching PySpark HashingTF
    3. Scaled numerical features
    4. Combined features logistic regression sigmoid
    """
    categories = metadata["categories"]
    verified_opts = metadata["verified_options"]
    num_features = metadata["num_features"]
    scaler_mean = np.array(metadata["scaler_mean"])
    scaler_std = np.array(metadata["scaler_std"])
    coeffs = np.array(metadata["lr_coefficients"])
    intercept = metadata["lr_intercept"]

    # 1. Categorical OHE
    cat_ohe = np.zeros(len(categories))
    if category in categories:
        cat_ohe[categories.index(category)] = 1.0

    ver_ohe = np.zeros(len(verified_opts))
    if verified_purchase in verified_opts:
        ver_ohe[verified_opts.index(verified_purchase)] = 1.0

    # 2. Text TF-IDF
    cleaned = re.sub(r"[^a-zA-Z0-9\s]", " ", review_text.lower()).strip()
    tokens = [w for w in cleaned.split() if len(w) > 0 and w not in ENGLISH_STOPWORDS]
    
    tf = np.zeros(num_features)
    for tok in tokens:
        if word_map and tok in word_map:
            h = word_map[tok]
        else:
            h = abs(hash(tok)) % num_features
        tf[h] += 1.0

    idf = np.array(metadata.get("idf_vector", [1.0] * num_features))
    text_vec = tf * idf

    # 3. Numerical Scaled
    num_raw = np.array([float(price), float(review_count), float(avg_rating)])
    num_scaled = np.zeros(3)
    for i in range(3):
        if scaler_std[i] > 1e-7:
            num_scaled[i] = (num_raw[i] - scaler_mean[i]) / scaler_std[i]
        else:
            num_scaled[i] = 0.0

    # 4. Final Vector Assembly: [cat_vec, verified_vec, text_idf, num_scaled]
    final_vec = np.concatenate([cat_ohe, ver_ohe, text_vec, num_scaled])

    # Dot product + intercept
    min_len = min(len(final_vec), len(coeffs))
    z = np.dot(final_vec[:min_len], coeffs[:min_len]) + intercept
    
    prob_high = 1.0 / (1.0 + np.exp(-np.clip(z, -30, 30)))
    prob_low = 1.0 - prob_high

    predicted_label = 1 if prob_high >= 0.5 else 0
    return predicted_label, prob_high, prob_low


